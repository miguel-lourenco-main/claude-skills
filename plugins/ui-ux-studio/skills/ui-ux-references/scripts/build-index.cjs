#!/usr/bin/env node
/**
 * build-index.cjs — scan the vault's reference notes and regenerate:
 *   - vault/_index.json        (fast, committed query cache read by query.py)
 *   - vault/Indexes/<Cat>.md   (per-category MOC; rewrites only the static-table region)
 *   - vault/Indexes/_All References.md
 * Dependency-free (uses scripts/lib/frontmatter.cjs).
 */
'use strict';
const fs = require('fs');
const path = require('path');
const fm = require('./lib/frontmatter.cjs');
const { resolveVault } = require('./lib/vault.cjs');

const ROOT = path.resolve(__dirname, '..');
// Vault is data, not code — resolved OUTSIDE the plugin (see lib/vault.cjs).
const VAULT = resolveVault(ROOT);
const REFS = path.join(VAULT, 'References');
const INDEXES = path.join(VAULT, 'Indexes');

function walkNotes() {
  const out = [];
  if (!fs.existsSync(REFS)) return out;
  for (const cat of fs.readdirSync(REFS)) {
    const cdir = path.join(REFS, cat);
    if (!fs.statSync(cdir).isDirectory()) continue;
    for (const slug of fs.readdirSync(cdir)) {
      const note = path.join(cdir, slug, `${slug}.md`);
      if (fs.existsSync(note)) out.push({ cat, slug, note });
    }
  }
  return out;
}

function section(body, name) {
  const re = new RegExp(`^##\\s+${name}\\s*$([\\s\\S]*?)(?=^##\\s|%%|<!--|$)`, 'mi');
  const m = re.exec(body);
  return m ? m[1].replace(/_\(pending[^)]*\)_/gi, '').replace(/\s+/g, ' ').trim() : '';
}
const num = (v) => { const n = parseFloat(v); return Number.isFinite(n) ? n : 0; };
const rel = (p) => path.relative(VAULT, p).split(path.sep).join('/');

// Every screenshot the extractor left at the top level of assets/ (downloaded page
// images live in assets/images/ and are NOT screenshots). Viewport first, then the
// full page, then any extra captures alphabetically — the gallery shows all of them.
const SHOT_RE = /\.(jpe?g|png|webp|avif)$/i;
const SHOT_ORDER = ['above-fold', 'full'];
function screenshots(assets) {
  if (!fs.existsSync(assets)) return [];
  const rank = (f) => { const i = SHOT_ORDER.indexOf(f.replace(SHOT_RE, '')); return i < 0 ? SHOT_ORDER.length : i; };
  return fs.readdirSync(assets)
    .filter((f) => SHOT_RE.test(f) && fs.statSync(path.join(assets, f)).isFile())
    .sort((a, b) => rank(a) - rank(b) || a.localeCompare(b))
    .map((f) => rel(path.join(assets, f)));
}

function build() {
  const records = [];
  for (const { cat, slug, note } of walkNotes()) {
    const { data, body } = fm.parse(fs.readFileSync(note, 'utf8'));
    const dir = path.dirname(note);
    const assets = path.join(dir, 'assets');
    records.push({
      slug, category: data.category || cat, title: data.title || slug, url: data.url || '',
      source: data.source || '', captured: data.captured || '', quality: num(data.quality),
      status: data.status || 'ok',
      tags: Array.isArray(data.tags) ? data.tags : [], palette: Array.isArray(data.palette) ? data.palette : [],
      heading_font: data.heading_font || '', body_font: data.body_font || '',
      images_count: num(data.images_count), css_count: num(data.css_count), js_count: num(data.js_count),
      style_text: section(body, 'Style'), strengths_text: section(body, 'Strengths'),
      patterns_text: section(body, 'Notable patterns'), when_to_use: section(body, 'When to use'),
      note: rel(note),
      above_fold: rel(path.join(dir, 'assets/above-fold.jpg')),
      full: rel(path.join(dir, 'assets/full.jpg')),
      raw_html: rel(path.join(dir, 'assets/raw.html')),
      rendered_html: rel(path.join(dir, 'assets/rendered.html')),
      screenshots: screenshots(assets),
    });
  }
  records.sort((a, b) => (a.category + a.slug).localeCompare(b.category + b.slug));
  fs.writeFileSync(path.join(VAULT, '_index.json'), JSON.stringify(records, null, 2));
  return records;
}

function staticTable(rows) {
  const lines = ['| Note | Q | Tags | URL |', '|---|---|---|---|'];
  for (const r of rows) lines.push(`| [[${r.slug}]] | ${r.quality} | ${(r.tags || []).filter((t) => t !== 'ui-reference').join(', ')} | ${r.url} |`);
  return lines.join('\n');
}

function writeMoc(file, title, category, rows) {
  const begin = '<!-- BEGIN STATIC INDEX -->', end = '<!-- END STATIC INDEX -->';
  const dvFrom = category ? `FROM #ui-reference AND "References/${category}"` : 'FROM #ui-reference';
  const table = staticTable(rows);
  if (fs.existsSync(file)) {
    let md = fs.readFileSync(file, 'utf8');
    const re = new RegExp(`${begin}[\\s\\S]*?${end}`);
    md = re.test(md) ? md.replace(re, `${begin}\n${table}\n${end}`) : md.replace(/\n*$/, '\n\n') + `${begin}\n${table}\n${end}\n`;
    fs.writeFileSync(file, md);
  } else {
    fs.writeFileSync(file, [
      '---', `title: ${JSON.stringify(title)}`, category ? `category: ${category}` : 'category: all', 'type: moc', '---', '',
      `# ${title}`, '',
      '```dataview', `TABLE quality AS "Q", join(tags, ", ") AS tags, url`, dvFrom, 'SORT quality DESC', '```', '',
      '%% Static fallback (regenerated by build-index.cjs; works with Dataview disabled) %%',
      begin, table, end, '',
    ].join('\n'));
  }
}

function main() {
  const records = build();
  fs.mkdirSync(INDEXES, { recursive: true });
  const byCat = {};
  for (const r of records) (byCat[r.category] ||= []).push(r);
  for (const [cat, rows] of Object.entries(byCat)) {
    const title = cat.charAt(0).toUpperCase() + cat.slice(1) + ' references';
    writeMoc(path.join(INDEXES, `${cat.charAt(0).toUpperCase() + cat.slice(1)}.md`), title, cat, rows.sort((a, b) => b.quality - a.quality));
  }
  writeMoc(path.join(INDEXES, '_All References.md'), 'All references', null, [...records].sort((a, b) => b.quality - a.quality));
  console.log(`Indexed ${records.length} reference(s) across ${Object.keys(byCat).length} categ/ies -> vault/_index.json + Indexes/`);
}

main();
