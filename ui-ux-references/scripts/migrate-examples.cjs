#!/usr/bin/env node
/**
 * migrate-examples.cjs — one-shot: convert legacy examples/<cat>/<slug>/{meta.json,*.jpg,snapshot.html}
 * into vault notes at vault/References/<cat>/<slug>/{<slug>.md, assets/...}.
 * Maps the meta.json teardown into note frontmatter + sections. Does NOT delete examples/
 * (review, then `rm -rf examples`). Re-run safe (overwrites notes/assets).
 */
'use strict';
const fs = require('fs');
const path = require('path');
const fm = require('./lib/frontmatter.cjs');

const ROOT = path.resolve(__dirname, '..');
const EXAMPLES = path.join(ROOT, 'examples');
const VAULT = path.join(ROOT, 'vault');
const FM_ORDER = ['title', 'url', 'category', 'source', 'captured', 'quality', 'status', 'slug', 'tags', 'palette', 'heading_font', 'body_font', 'images_count', 'css_count', 'js_count'];

const kebab = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '').slice(0, 40);
const bullets = (arr) => (arr && arr.length ? arr.map((x) => `- ${x}`).join('\n') : '_(none)_');
const ordered = (arr) => (arr && arr.length ? arr.map((x, i) => `${i + 1}. ${x}`).join('\n') : '_(none)_');

function noteBody(m) {
  const ty = m.typography || {};
  return [
    `# ${m.title || m.slug}`, '',
    `> [${m.url}](${m.url}) · [[${m.category}]] · captured ${m._captured} · quality ${m.quality_score ?? 0}/100`, '',
    '## Above the fold', '![[assets/above-fold.jpg]]', '',
    '## Full page', '![[assets/full.jpg]]', '',
    '%% TEARDOWN:START — edited by the LLM teardown step %%',
    '## Style', bullets(m.style_tags), '',
    '## Palette', bullets(m.palette), '',
    '## Typography', `- **Heading:** ${ty.heading || '_(n/a)_'}`, `- **Body:** ${ty.body || '_(n/a)_'}`, `- **Feel:** ${ty.feel || '_(n/a)_'}`, '',
    '## Layout sections', ordered(m.layout_sections), '',
    '## Strengths', bullets(m.strengths), '',
    '## Weaknesses', bullets(m.weaknesses), '',
    '## Notable patterns', bullets(m.notable_patterns), '',
    '## When to use', m.when_to_use || '_(n/a)_',
    '%% TEARDOWN:END %%', '',
    '%% CAPTURE:START — regenerated by extract.cjs; do not edit by hand %%',
    '## Raw materials',
    '- Legacy capture (screenshots + rendered HTML only). Re-run `extract.cjs --url <url>` to add raw HTML / images / css / js.',
    '- [Rendered DOM](assets/rendered.html)',
    '%% CAPTURE:END %%', '',
  ].join('\n');
}

function migrate() {
  if (!fs.existsSync(EXAMPLES)) { console.log('No examples/ to migrate.'); return; }
  let n = 0;
  for (const cat of fs.readdirSync(EXAMPLES)) {
    const cdir = path.join(EXAMPLES, cat);
    if (!fs.statSync(cdir).isDirectory()) continue;
    for (const slug of fs.readdirSync(cdir)) {
      const sdir = path.join(cdir, slug);
      const metaPath = path.join(sdir, 'meta.json');
      if (!fs.existsSync(metaPath)) continue;
      const m = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
      if (m.status && m.status !== 'ok') continue;
      m.category = m.category || cat; m.slug = m.slug || slug;
      m._captured = (m.captured_at || m.teardown_at || '').slice(0, 10) || '2026-06-13';

      const dest = path.join(VAULT, 'References', m.category, slug);
      const assets = path.join(dest, 'assets');
      fs.mkdirSync(assets, { recursive: true });
      for (const [src, dst] of [['above-fold.jpg', 'above-fold.jpg'], ['full.jpg', 'full.jpg'], ['snapshot.html', 'rendered.html']]) {
        const s = path.join(sdir, src);
        if (fs.existsSync(s)) fs.copyFileSync(s, path.join(assets, dst));
      }

      const tags = ['ui-reference', m.category, ...(m.style_tags || []).slice(0, 5).map(kebab)].filter((t, i, a) => t && a.indexOf(t) === i);
      const data = {
        title: m.title || slug, url: m.url || '', category: m.category, source: m.source || 'onepagelove',
        captured: m._captured, quality: m.quality_score ?? 0, status: 'ok', slug,
        tags, palette: m.palette || [], heading_font: (m.typography || {}).heading || '', body_font: (m.typography || {}).body || '',
        images_count: 0, css_count: 0, js_count: 0,
      };
      fs.writeFileSync(path.join(dest, `${slug}.md`), fm.stringify(data, FM_ORDER) + noteBody(m));
      console.log(`  migrated ${m.category}/${slug}`);
      n++;
    }
  }
  console.log(`\nMigrated ${n} reference(s) -> vault/References/. Review, then: rm -rf examples && node scripts/build-index.cjs`);
}

migrate();
